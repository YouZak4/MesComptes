-- Schéma initial de MesComptes.
--
-- Depuis l'ADR 0008, toute modification de la base passe par Flyway et Hibernate ne fait que
-- vérifier le schéma (ddl-auto=validate). Ce script regroupe l'état de la base au 2026-11-25 :
-- il remplace les anciennes migrations V1 à V3 et le schéma créé jusque-là par Hibernate.
-- Il a été écrit à partir de la base de développement, avec des noms de contraintes explicites.
--
-- Conventions de nommage : pk_<table>, fk_<table>_<cible>, uk_<table>_<colonnes>,
-- ck_<table>_<règle>, idx_<table>_<colonnes>.

-- Utilisateurs et rôles ------------------------------------------------------------------------

CREATE TABLE utilisateurs (
    id           UUID         NOT NULL,
    identifiant  VARCHAR(255) NOT NULL,
    email        VARCHAR(255) NOT NULL,
    mot_de_passe VARCHAR(255) NOT NULL,
    nom          VARCHAR(255) NOT NULL,
    prenom       VARCHAR(255),
    CONSTRAINT pk_utilisateurs       PRIMARY KEY (id),
    CONSTRAINT uk_utilisateurs_email UNIQUE (email)
);

CREATE TABLE role (
    id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nom VARCHAR(255) NOT NULL,
    CONSTRAINT pk_role     PRIMARY KEY (id),
    CONSTRAINT uk_role_nom UNIQUE (nom)
);

CREATE TABLE utilisateur_roles (
    utilisateur_id UUID   NOT NULL,
    role_id        BIGINT NOT NULL,
    CONSTRAINT pk_utilisateur_roles             PRIMARY KEY (utilisateur_id, role_id),
    CONSTRAINT fk_utilisateur_roles_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id),
    CONSTRAINT fk_utilisateur_roles_role        FOREIGN KEY (role_id) REFERENCES role (id)
);

-- Inscription et changement d'adresse mail en attente de vérification par code -----------------

CREATE TABLE inscriptions_en_attente (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    jeton           VARCHAR(255) NOT NULL,
    identifiant     VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    mot_de_passe    VARCHAR(255) NOT NULL,
    nom             VARCHAR(255) NOT NULL,
    prenom          VARCHAR(255),
    compte_existant BOOLEAN      NOT NULL,
    code_hash       VARCHAR(255) NOT NULL,
    tentatives      INTEGER      NOT NULL,
    dernier_envoi   TIMESTAMP(6) NOT NULL,
    expiration      TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_inscriptions_en_attente       PRIMARY KEY (id),
    CONSTRAINT uk_inscriptions_en_attente_jeton UNIQUE (jeton),
    CONSTRAINT uk_inscriptions_en_attente_email UNIQUE (email)
);

CREATE TABLE changements_email (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    utilisateur_id  UUID         NOT NULL,
    nouvel_email    VARCHAR(255) NOT NULL,
    email_deja_pris BOOLEAN      NOT NULL,
    code_hash       VARCHAR(255) NOT NULL,
    tentatives      INTEGER      NOT NULL,
    dernier_envoi   TIMESTAMP(6) NOT NULL,
    expiration      TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_changements_email             PRIMARY KEY (id),
    CONSTRAINT uk_changements_email_utilisateur UNIQUE (utilisateur_id),
    CONSTRAINT fk_changements_email_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id)
);

-- Comptes et périodes --------------------------------------------------------------------------

CREATE TABLE compte (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    utilisateur_id     UUID           NOT NULL,
    nom                VARCHAR(255)   NOT NULL,
    solde_initial      NUMERIC(12, 2) NOT NULL,
    date_solde_initial DATE           NOT NULL,
    archive            BOOLEAN        NOT NULL,
    CONSTRAINT pk_compte             PRIMARY KEY (id),
    CONSTRAINT fk_compte_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id)
);

-- Une période n'est pas référencée par les opérations : elle se déduit de leur date (ADR 0001).
CREATE TABLE periode (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    utilisateur_id UUID         NOT NULL,
    nom            VARCHAR(255) NOT NULL,
    date_debut     DATE         NOT NULL,
    date_fin       DATE         NOT NULL,
    CONSTRAINT pk_periode             PRIMARY KEY (id),
    CONSTRAINT uk_periode_debut       UNIQUE (utilisateur_id, date_debut),
    CONSTRAINT ck_periode_dates       CHECK (date_fin >= date_debut),
    CONSTRAINT fk_periode_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id)
);

-- Catégories, libellés et masquage -------------------------------------------------------------

-- utilisateur_id vide : catégorie fournie, commune à tous les utilisateurs.
CREATE TABLE categorie (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    utilisateur_id UUID,
    nom            VARCHAR(50)  NOT NULL,
    nom_normalise  VARCHAR(255) NOT NULL,
    type           VARCHAR(10)  NOT NULL,
    couleur        VARCHAR(7),
    icone          VARCHAR(255),
    archive        BOOLEAN      NOT NULL,
    CONSTRAINT pk_categorie             PRIMARY KEY (id),
    CONSTRAINT uk_categorie_nom         UNIQUE (utilisateur_id, nom_normalise),
    CONSTRAINT ck_categorie_type        CHECK (type IN ('DEPENSE', 'REVENU')),
    CONSTRAINT fk_categorie_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id)
);

-- utilisateur_id vide : libellé fourni, commun à tous les utilisateurs.
CREATE TABLE libelle (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    utilisateur_id UUID,
    categorie_id   BIGINT       NOT NULL,
    nom            VARCHAR(255) NOT NULL,
    nom_normalise  VARCHAR(255) NOT NULL,
    archive        BOOLEAN      NOT NULL,
    CONSTRAINT pk_libelle             PRIMARY KEY (id),
    CONSTRAINT uk_libelle_nom         UNIQUE (utilisateur_id, nom_normalise),
    CONSTRAINT fk_libelle_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id),
    CONSTRAINT fk_libelle_categorie   FOREIGN KEY (categorie_id) REFERENCES categorie (id)
);

-- Un utilisateur masque une catégorie ou un libellé fourni (element_id selon type_element).
CREATE TABLE masquage (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    utilisateur_id UUID        NOT NULL,
    type_element   VARCHAR(10) NOT NULL,
    element_id     BIGINT      NOT NULL,
    CONSTRAINT pk_masquage              PRIMARY KEY (id),
    CONSTRAINT uk_masquage              UNIQUE (utilisateur_id, type_element, element_id),
    CONSTRAINT ck_masquage_type_element CHECK (type_element IN ('CATEGORIE', 'LIBELLE')),
    CONSTRAINT fk_masquage_utilisateur  FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id)
);

-- Récurrences et opérations --------------------------------------------------------------------

CREATE TABLE recurrence (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    utilisateur_id       UUID           NOT NULL,
    compte_id            BIGINT         NOT NULL,
    categorie_id         BIGINT         NOT NULL,
    libelle_id           BIGINT,
    type                 VARCHAR(10)    NOT NULL,
    montant              NUMERIC(12, 2) NOT NULL,
    note                 VARCHAR(255),
    frequence            VARCHAR(10)    NOT NULL,
    jour                 INTEGER        NOT NULL,
    date_debut           DATE           NOT NULL,
    date_fin             DATE,
    prochaine_occurrence DATE           NOT NULL,
    CONSTRAINT pk_recurrence             PRIMARY KEY (id),
    CONSTRAINT ck_recurrence_montant     CHECK (montant > 0),
    CONSTRAINT ck_recurrence_jour        CHECK (jour BETWEEN 1 AND 31),
    CONSTRAINT ck_recurrence_type        CHECK (type IN ('DEPENSE', 'REVENU')),
    CONSTRAINT ck_recurrence_frequence   CHECK (frequence IN ('MENSUELLE', 'ANNUELLE')),
    CONSTRAINT fk_recurrence_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id),
    CONSTRAINT fk_recurrence_compte      FOREIGN KEY (compte_id) REFERENCES compte (id),
    CONSTRAINT fk_recurrence_categorie   FOREIGN KEY (categorie_id) REFERENCES categorie (id),
    CONSTRAINT fk_recurrence_libelle     FOREIGN KEY (libelle_id) REFERENCES libelle (id)
);

CREATE TABLE operation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    compte_id     BIGINT         NOT NULL,
    categorie_id  BIGINT         NOT NULL,
    libelle_id    BIGINT,
    recurrence_id BIGINT,
    type          VARCHAR(10)    NOT NULL,
    montant       NUMERIC(12, 2) NOT NULL,
    date          DATE           NOT NULL,
    note          VARCHAR(255),
    CONSTRAINT pk_operation              PRIMARY KEY (id),
    -- Une récurrence ne génère qu'une opération par date.
    CONSTRAINT uk_operation_recurrence_date UNIQUE (recurrence_id, date),
    CONSTRAINT ck_operation_montant      CHECK (montant > 0),
    CONSTRAINT ck_operation_type         CHECK (type IN ('DEPENSE', 'REVENU')),
    CONSTRAINT fk_operation_compte       FOREIGN KEY (compte_id) REFERENCES compte (id),
    CONSTRAINT fk_operation_categorie    FOREIGN KEY (categorie_id) REFERENCES categorie (id),
    CONSTRAINT fk_operation_libelle      FOREIGN KEY (libelle_id) REFERENCES libelle (id),
    CONSTRAINT fk_operation_recurrence   FOREIGN KEY (recurrence_id) REFERENCES recurrence (id)
);

-- Les opérations se lisent par compte et par intervalle de dates (périodes, tableau de bord).
CREATE INDEX idx_operation_compte_date ON operation (compte_id, date);
